defmodule Ecto.Hosi.NativeTest do
  use Ecto.Hosi.Case, async: true

  describe "history, highest, erase" do
    test "history is every event of one entity" do
      user = Repo.insert!(%User{name: "Ada", email: "a@x"})
      {:ok, _} = user |> User.changeset(%{name: "Augusta"}) |> Repo.update()

      names = for %{attr: :"user/name", val: v} <- Repo.history(user.id), do: v
      assert names == ["Ada", "Augusta"]
    end

    test "highest pages newest-first and returns structs" do
      for {t, n} <- [{"a", 5}, {"b", 9}, {"c", 1}, {"d", 7}],
          do: Repo.insert!(%Post{title: t, likes: n})

      {page, last} = Repo.highest(Post, :likes, 2)
      assert Enum.map(page, & &1.title) == ["b", "d"]
      assert %Post{} = hd(page)
      assert hd(page).likes == 9

      {next, _} = Repo.highest(Post, :likes, 2, after: last)
      assert Enum.map(next, & &1.title) == ["a", "c"]
    end

    test "highest_in walks the newest rows of some keys" do
      a = Repo.insert!(%User{name: "A", email: "a@y"})
      b = Repo.insert!(%User{name: "B", email: "b@y"})
      c = Repo.insert!(%User{name: "C", email: "c@y"})
      t = fn n -> DateTime.add(~U[2026-01-01 00:00:00.000000Z], n, :second) end

      for {u, title, n} <- [{a, "a1", 1}, {b, "b2", 2}, {a, "a3", 3}, {c, "c4", 4}, {b, "b5", 5}] do
        Repo.insert!(%Post{title: title, user_id: u.id, inserted_at: t.(n), updated_at: t.(n)})
      end

      page = Repo.highest_in(Post, {:user_id, :inserted_at}, [a.id, b.id], 3)
      assert Enum.map(page, & &1.key) == [b.id, a.id, b.id]
      assert Enum.map(page, & &1.at) == [t.(5), t.(3), t.(2)]

      next = Repo.highest_in(Post, {:user_id, :inserted_at}, [a.id, b.id], 3, after: List.last(page))
      assert Enum.map(next, & &1.at) == [t.(1)]
    end

    test "a row with a hosi_tuple index can be deleted, bulk-deleted and rolled back" do
      u = Repo.insert!(%User{name: "T", email: "t@y"})
      p1 = Repo.insert!(%Post{title: "p1", user_id: u.id})
      p2 = Repo.insert!(%Post{title: "p2", user_id: u.id})
      p3 = Repo.insert!(%Post{title: "p3", user_id: u.id})

      assert {:ok, _} = Repo.delete(p1)
      assert {1, _} = Ecto.Query.from(p in Post, where: p.id == ^p2.id) |> Repo.delete_all()

      assert {:error, :nope} = Repo.transaction(fn -> Repo.delete!(p3) |> then(fn _ -> Repo.rollback(:nope) end) end)
      assert Repo.get(Post, p3.id)
    end

    test "erase removes the entity" do
      user = Repo.insert!(%User{name: "Gone", email: "g@x"})
      Repo.erase([[:ids, [user.id]]])
      assert Repo.get(User, user.id) == nil
    end
  end

  describe "write_batch" do
    test "a parent and a child in one atomic write, the child pointing at the parent" do
      assert {:ok, %{user: user, post: post}} =
               Repo.write_batch(
                 insert: {:user, User.changeset(%User{}, %{name: "Ada", email: "a@x"})},
                 insert:
                   {:post, Post.changeset(%Post{}, %{title: "Notes"}), refs: [user_id: :user]}
               )

      assert is_integer(user.id) and is_integer(post.id)
      assert post.user_id == user.id
      assert user.inserted_at, "autogenerated timestamps are filled"

      assert Repo.get!(Post, post.id).user_id == user.id
      assert Repo.get!(User, user.id) |> Repo.preload(:posts) |> Map.get(:posts) |> length() == 1
      assert facts()[{post.id, :"post/user_id"}] == [user.id]
    end

    test "an invalid changeset stops everything before any write" do
      bad = User.changeset(%User{}, %{})
      good = User.changeset(%User{}, %{name: "Ok", email: "ok@x"})

      assert {:error, :first, %Ecto.Changeset{valid?: false}} =
               Repo.write_batch(insert: {:first, bad}, insert: {:second, good})

      assert Repo.aggregate(User, :count) == 0
    end

    test "a taken unique value comes back on that step's changeset, and nothing is written" do
      Repo.insert!(%User{name: "Taken", email: "t@x"})

      assert {:error, :dup, cs} =
               Repo.write_batch(
                 insert: {:fine, User.changeset(%User{}, %{name: "Fine", email: "f@x"})},
                 insert: {:dup, User.changeset(%User{}, %{name: "Dup", email: "t@x"})}
               )

      assert cs.errors[:email]
      assert Repo.aggregate(User, :count) == 1
    end

    test "if a row changed under it, the whole batch is stale and writes nothing" do
      ada = Repo.insert!(%User{name: "Ada", email: "a@x"})
      Repo.delete!(ada)

      assert {:error, :batch, :stale} =
               Repo.write_batch(
                 insert: {:new, User.changeset(%User{}, %{name: "New", email: "n@x"})},
                 update: {:old, User.changeset(ada, %{name: "Ghost"})}
               )

      assert Repo.aggregate(User, :count) == 0
    end

    test "inserts, an update and a delete together" do
      keep = Repo.insert!(%User{name: "Keep", email: "k@x"})
      drop = Repo.insert!(%User{name: "Drop", email: "d@x"})

      assert {:ok, res} =
               Repo.write_batch(
                 insert: {:new, User.changeset(%User{}, %{name: "New", email: "n@x"})},
                 update: {:keep, User.changeset(keep, %{name: "Kept"})},
                 delete: {:drop, drop}
               )

      assert res.drop.__meta__.state == :deleted
      assert res.keep.name == "Kept"
      assert Repo.all(from(u in User, select: u.name)) |> Enum.sort() == ["Kept", "New"]
    end

    test "refs must point at an earlier insert" do
      assert_raise ArgumentError, ~r/earlier in the batch/, fn ->
        Repo.write_batch(
          insert: {:post, Post.changeset(%Post{}, %{title: "T"}), refs: [user_id: :user]},
          insert: {:user, User.changeset(%User{}, %{name: "A", email: "a@x"})}
        )
      end
    end
  end

  describe "schema building" do
    test "rejects what hosigraph cannot keep, with the reason" do
      defmodule BadKey do
        use Ecto.Schema
        @primary_key {:id, :binary_id, autogenerate: true}
        schema "bad_key" do
          field(:x, :integer)
        end
      end

      defmodule BadType do
        use Ecto.Schema

        schema "bad_type" do
          field(:data, Ecto.UUID)
        end
      end

      assert_raise ArgumentError, ~r/integer primary key named :id/, fn ->
        Ecto.Hosi.Schema.build([BadKey])
      end

      assert_raise ArgumentError, ~r/does not support the Ecto type Ecto.UUID/, fn ->
        Ecto.Hosi.Schema.build([BadType])
      end
    end
  end
end
